use crate::git::{self, Git};
use anyhow::{bail, Context, Result};
use std::fs;
use std::path::PathBuf;

/// Called by the installed `pre-commit` hook. Returns `false` when the commit
/// must be blocked.
pub fn pre_commit() -> Result<bool> {
    let repo = git::discover()?;
    let git = Git::new(repo);
    let branch = git
        .try_run(&["symbolic-ref", "--short", "HEAD"])?
        .unwrap_or_default();

    if branch == "master" || branch == "main" {
        eprintln!(
            "COMMIT BLOCKED: branch '{}' is protected - no direct commits.",
            branch
        );
        eprintln!("Create a worktree for the task:");
        eprintln!("  cargo run -p sonixx-dev -- worktree open feat/my-task");
        Ok(false)
    } else {
        Ok(true)
    }
}

pub fn init(force: bool) -> Result<()> {
    let repo = git::discover()?;
    let principal = git::principal_of(&repo);
    let git = Git::new(&principal);
    let protected = git::protected_branch(&git)?;
    let common = git::git_common_dir(&git)?;

    // Respect a custom core.hooksPath (some repos keep hooks in .githooks).
    let hooks_dir = match git.try_run(&["config", "--get", "core.hooksPath"])? {
        Some(raw) if !raw.trim().is_empty() => {
            let path = PathBuf::from(raw.trim());
            if path.is_absolute() {
                path
            } else {
                principal.join(path)
            }
        }
        _ => common.join("hooks"),
    };
    fs::create_dir_all(&hooks_dir)
        .with_context(|| format!("failed to create hooks folder {}", hooks_dir.display()))?;

    // Keep a copy of this CLI inside .git so cleanup can survive the removal of
    // a worktree (and so the hook does not depend on cargo being on PATH).
    let exe_name = if cfg!(windows) {
        "sonixx-dev.exe"
    } else {
        "sonixx-dev"
    };
    let installed = common.join(exe_name);
    let current = std::env::current_exe().context("cannot locate the running sonixx-dev binary")?;
    let hook_exe = if git::same_path(&current, &installed) {
        installed.clone()
    } else {
        match fs::copy(&current, &installed) {
            Ok(_) => installed.clone(),
            Err(err) => {
                eprintln!(
                    "warning: could not copy sonixx-dev to {} ({err}); the hook will use {}",
                    installed.display(),
                    current.display()
                );
                current
            }
        }
    };

    let hook_path = hooks_dir.join("pre-commit");
    if hook_path.exists() && !force {
        let existing = fs::read_to_string(&hook_path).unwrap_or_default();
        if !existing.contains("sonixx-dev") {
            bail!(
                "a different pre-commit hook already exists at {}.\nRe-run with --force to replace it.",
                hook_path.display()
            );
        }
    }

    let exe_for_shell = hook_exe.to_string_lossy().replace('\\', "/");
    let script = format!(
        r#"#!/bin/sh
# Generated by sonixx-dev init - protects master/main from direct commits.
if [ -x "{exe}" ]; then
  exec "{exe}" hook pre-commit
fi
branch=$(git symbolic-ref --short HEAD 2>/dev/null)
case "$branch" in
  main|master)
    echo "COMMIT BLOCKED: branch '$branch' is protected - no direct commits."
    echo "Create a worktree: cargo run -p sonixx-dev -- worktree open feat/my-task"
    exit 1
    ;;
esac
exit 0
"#,
        exe = exe_for_shell
    );
    fs::write(&hook_path, script)
        .with_context(|| format!("failed to write hook {}", hook_path.display()))?;

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = fs::metadata(&hook_path)?.permissions();
        perms.set_mode(0o755);
        fs::set_permissions(&hook_path, perms)?;
    }

    println!("Hook installed: {}", hook_path.display());
    println!("Protected branch: {protected}");
    println!("CLI copy: {}", hook_exe.display());

    let gitignore = principal.join(".gitignore");
    if let Ok(text) = fs::read_to_string(&gitignore) {
        let has_worktrees = text
            .lines()
            .any(|line| matches!(line.trim(), ".worktrees/" | ".worktrees"));
        if !has_worktrees {
            println!("NOTE: add '.worktrees/' to .gitignore so task folders stay out of git.");
        }
    }

    println!();
    println!("Test it from the main copy (it must fail):");
    println!("  git commit --allow-empty -m test");
    Ok(())
}
